%% OPCUS four-fiber weighted random transmit-point selection + automatic copying of the corresponding DMD patterns


clear; close all; clc;

% Random number seed 
rng(100);


%% ====================== User Configuration ======================
fiber_paths = {
    "..\..\..\data\prior-guided dynamic imaging\full-transmit RF data\filtered_data0.mat";
    "..\..\..\data\prior-guided dynamic imaging\full-transmit RF data\filtered_data0.mat";
    "..\..\..\data\prior-guided dynamic imaging\full-transmit RF data\filtered_data0.mat";
    "..\..\..\data\prior-guided dynamic imaging\full-transmit RF data\filtered_data0.mat"
};

num_fibers = numel(fiber_paths);     % Automatically detect the number of fibers

N_select = 375;                      % Target number of sampling points
apply_spacing = true;                % Whether to apply the minimum-spacing constraint
min_spacing = 1e-4/2;                % Minimum hard spacing, in m; currently 50 um

%% ====================== Pattern Copying Configuration ======================
% Set this flag to true to automatically find and copy the corresponding Python patterns after point selection.
copy_selected_patterns_flag = true;

% Directory containing the 101x101 full-field TIFF patterns generated by the Python script.
% Default output directory of the original Python code:
% ./pad_Direct_gene_slope_2D_sequence_saved_center_big_lateral_75um_divide_2_center_half_100_100
%
% If the MATLAB current working directory differs from the Python runtime directory, change this to an absolute path.
pattern_source_dir = ...
    'C:\Users\admin\Desktop\full_transmit_pattern';

% Destination directory for the copied files.
% If left empty, the program automatically generates a directory based on the actual N_select.
pattern_output_dir = 'C:\Users\admin\Desktop\prior_guided_pattern';


% If TIFF files already exist in the destination folder:
% false -> raise an error to avoid mixing in an old sequence;
% true  -> allow overwriting files with the same name, but other old files are not deleted.
allow_existing_tif_in_output = false;

% Whether to strictly verify that big_x/y in the Python file names match the theoretical row/col mapping.
% Keeping this true is recommended.
strict_pattern_mapping_check = true;

% Parameters from the Python pattern-generation script.
% These values are only used for "file mapping verification", not as actual physical focal parameters.
python_i0_start = 96 - 50;       % 46
python_j0_start = 92 - 50;       % 42
python_interval_x = 11/4;        % 2.75
python_interval_y = 20/4;        % 5
filename_xy_tolerance = 0.11;    % File names keep only 1 decimal place; leave rounding tolerance

%% ====================== System Parameters ======================
c = 1490;
dt = 1/(50e6);

dx = 0.04e-3;
dy = dx;
dz = dx;

grid_size = [250, 250, 250];

discrete_interval = [11*5/3/2/2, 20*5/3/2/2];

source_dx = 14.7e-3/1080 * discrete_interval(1);
source_dy = 14.7e-3/1920 * discrete_interval(2);

sensor_row = 101;
sensor_column = 101;

offset_x = (grid_size(1)*dx - sensor_row*14.7e-3/1080*discrete_interval(1))/2;
offset_y = (grid_size(2)*dx - sensor_column*14.7e-3/1080*discrete_interval(1))/2;

[J_grid, I_grid] = meshgrid(1:sensor_column, 1:sensor_row);

tx_pos = [J_grid(:)*source_dx + offset_x, ...
          I_grid(:)*source_dy + offset_y, ...
          ones(sensor_row*sensor_column,1)*dz];

a = size(tx_pos, 1);

fprintf('Total number of candidate transmit points: %d x %d = %d\n', sensor_row, sensor_column, a);
fprintf('Number of input fiber/result datasets: %d\n', num_fibers);

%% ====================== 1. Load the Four-Fiber Data and Extract Information Weights ======================
fprintf('\nLoading %d fiber datasets and computing Hilbert envelope variance...\n', num_fibers);

motion_all = zeros(a, num_fibers);

for f = 1:num_fibers

    fprintf('  Fiber %d / %d: %s\n', f, num_fibers, fiber_paths{f});

    tmp = load(fiber_paths{f});

    if isfield(tmp, 'filtered_data')
        pad_f = tmp.filtered_data;
    else
        error('File %s does not contain the variable filtered_data; please check the variable name.', fiber_paths{f});
    end

    % Preprocessing consistent with the original reconstruction code
    pad_f = pad_f(:,:,34:end);
    pad_f(:,:,1:470) = 0;
    % pad_f(1:17,:,1:310) = 0;
    % pad_f(:,:,620:end) = 0;

    % Check whether the first two dimensions match the number of transmit points
    if size(pad_f,1) ~= sensor_row || size(pad_f,2) ~= sensor_column
        error(['Fiber %d data size is %s, but the current setting is %d x %d; ' ...
               'please check sensor_row/sensor_column.'], ...
               f, mat2str(size(pad_f)), sensor_row, sensor_column);
    end

    % MATLAB column-major reshape:
    % The first dimension (row) varies fastest; the second dimension (column) varies more slowly
    data_f = reshape(pad_f, a, []);

    % Hilbert envelope
    env_f = abs(hilbert(data_f'));
    env_f = env_f';

    % Information weight of each transmit point: variance of the Hilbert envelope along the time dimension
    info_f = var(env_f, 0, 2);

    % Normalize within each fiber to [0,1]
    max_info = max(info_f, [], 'all');

    if max_info > 0
        info_f = info_f / max_info;
    else
        warning('The maximum info_f of fiber %d is 0; all weights of this fiber are set to zero.', f);
        info_f = zeros(size(info_f));
    end

    motion_all(:,f) = info_f;
end

%% ====================== 2. Four-Fiber Fusion ======================
% Average the information weights of the four fibers
motion_score = mean(motion_all, 2);

% Optional: reduce the concentration of high-weight points
% motion_score = motion_score.^0.5;

% Optional: fully random sampling, ignoring signal information
% motion_score = ones(size(motion_score));

sum_score = sum(motion_score);

if sum_score <= 0
    error('The sum of motion_score is 0; unable to generate motion_weight. Please check the input data or the preprocessing range.');
end

motion_weight = motion_score / sum_score;

fprintf('Fused weight range: [%.4e, %.4e]\n', min(motion_weight), max(motion_weight));

%% ====================== 3. Weighted Random Sampling ======================
fprintf('\nPerforming weighted random sampling (N = %d)...\n', N_select);

if ~apply_spacing

    %% ===== Pure weighted random sampling, no spatial constraint =====
    selected = zeros(N_select, 1);
    w_temp = motion_weight;
    available = true(a, 1);

    for iter = 1:N_select

        cumw = cumsum(w_temp(available));

        if isempty(cumw) || cumw(end) <= 0
            warning('Remaining selectable weights exhausted; terminated early at step %d.', iter);
            selected = selected(1:iter-1);
            break;
        end

        r = rand() * cumw(end);
        idx_rel = find(cumw >= r, 1, 'first');

        idx_all = find(available);
        selected(iter) = idx_all(idx_rel);

        % Remove the selected point to avoid duplication
        available(selected(iter)) = false;

        if mod(iter, 100) == 0
            fprintf('  Selected %d / %d points\n', iter, N_select);
        end
    end

    N_select = length(selected);
    fprintf('Pure weighted random sampling completed; %d points actually selected.\n', N_select);

else

    %% ===== Weighted random sampling + minimum-spacing constraint =====
    selected = zeros(N_select, 1);
    w_temp = motion_weight;
    tx_xy = tx_pos(:,1:2);

    actual_count = 0;

    for iter = 1:N_select

        sum_w = sum(w_temp);

        if sum_w < 1e-12
            warning('Remaining weights exhausted; terminated early at step %d.', iter);
            break;
        end

        w_temp = w_temp / sum_w;

        cumw = cumsum(w_temp);
        r = rand() * cumw(end);
        idx = find(cumw >= r, 1, 'first');

        actual_count = actual_count + 1;
        selected(actual_count) = idx;

        dx_s = tx_xy(:,1) - tx_xy(idx,1);
        dy_s = tx_xy(:,2) - tx_xy(idx,2);
        dist_s = sqrt(dx_s.^2 + dy_s.^2);

        % Exclude the current point and all points closer than min_spacing
        too_close = dist_s < min_spacing;
        too_close(idx) = true;

        w_temp(too_close) = 0;

        if mod(actual_count, 100) == 0
            fprintf('  Selected %d / %d points\n', actual_count, N_select);
        end
    end

    selected = selected(1:actual_count);
    N_select = length(selected);

    fprintf('Weighted random sampling + spacing constraint completed; %d points actually selected.\n', N_select);
end

%% ====================== 4. Result Organization ======================
% MATLAB column-major linear index -> row / column
rows = mod(selected - 1, sensor_row) + 1;
cols = floor((selected - 1) / sensor_row) + 1;

% Record the randomly selected positions as a 1 x k row vector.
% The MATLAB linear index (column-major) on the 101x101 grid is used here:
%   random_chosen_position = row + (col-1)*101
% Therefore, its relation to the 0-based index of the corresponding Python pattern is:
%   random_chosen_position = python_index0 + 1
random_chosen_position = reshape(selected, 1, []);

show_mat = reshape(motion_score, sensor_row, sensor_column);

%% ====================== 5. Weight Map Visualization ======================
sigma = 2;
blurred_mat = imgaussfilt(show_mat, sigma);
blurred_mat = mat2gray(blurred_mat);

figure(3);
imagesc(blurred_mat);
colormap(hot);
caxis([0 1]);
axis equal;
axis off;

cb = colorbar('horiz');
cb.Ticks = [0 1];
cb.TickLabels = {'0','1'};

print(gcf, './sample_weight_4fiber.png', '-dpng', '-r400');

%% ====================== 6. Sampling Result Visualization ======================
figure('Name', 'Four-fiber weighted random transmit-point selection', 'Position', [50 50 1400 450]);

subplot(1,3,1);
imagesc(reshape(motion_score, sensor_row, sensor_column));
colormap(hot);
colorbar;
hold on;

scatter(cols, rows, 60, 'g', 'filled', ...
    'MarkerEdgeColor', 'w', ...
    'LineWidth', 1);

title(sprintf('Four-fiber fused weights + %d selected points', N_select), 'FontSize', 12);
xlabel('Column (j)');
ylabel('Row (i)');
axis image;
set(gca, 'YDir', 'reverse', 'FontSize', 11);

subplot(1,3,2);
histogram(rows, 1:sensor_row+1, ...
    'FaceColor', 'r', ...
    'EdgeColor', 'none');

hold on;

histogram(cols, 1:sensor_column+1, ...
    'FaceColor', 'b', ...
    'EdgeColor', 'none', ...
    'FaceAlpha', 0.5);

title('Histogram of selected-point row/column distribution', 'FontSize', 12);
xlabel('Row/column index');
ylabel('Count');
legend('Row distribution', 'Column distribution', 'Location', 'best');
set(gca, 'FontSize', 11);

subplot(1,3,3);
tx_xy = tx_pos(:,1:2);

if length(selected) > 1
    dist_mat = squareform(pdist(tx_xy(selected,:)));
    imagesc(dist_mat);
    colorbar;
    colormap(jet);

    min_dist_mm = min(dist_mat(dist_mat > 0)) * 1e3;
    title(sprintf('Selected-point distance matrix\nMinimum spacing = %.2f mm', min_dist_mm), 'FontSize', 12);
else
    dist_mat = [];
    imagesc(0);
    title('Too few selected points to compute the distance matrix', 'FontSize', 12);
end

xlabel('Selection index');
ylabel('Selection index');
axis image;
set(gca, 'FontSize', 11);

%% ====================== 7. Save the Point-Selection Results ======================
save_name = sprintf('aous_weighted_random_4fiber_%dpts.mat', N_select);

save(save_name, ...
     'selected', ...
     'rows', ...
     'cols', ...
     'random_chosen_position', ...
     'motion_score', ...
     'motion_weight', ...
     'motion_all', ...
     'tx_pos', ...
     'N_select', ...
     'apply_spacing', ...
     'min_spacing', ...
     'fiber_paths', ...
     'num_fibers', ...
     'sensor_row', ...
     'sensor_column', ...
     'source_dx', ...
     'source_dy', ...
     'offset_x', ...
     'offset_y', ...
     'dist_mat');

fprintf('\nResults saved to %s\n', save_name);

%% ====================== 8. Copy the Corresponding Python DMD Patterns by Selected Positions ======================
if copy_selected_patterns_flag

    fprintf('\n============================================================\n');
    fprintf('Starting to copy the corresponding Python DMD patterns based on the MATLAB selection results...\n');
    fprintf('============================================================\n');

    if sensor_row ~= 101 || sensor_column ~= 101
        error(['The current pattern mapping targets Python-generated 101x101 sequences. ' ...
               'The current MATLAB setting is %d x %d; please confirm the mapping first.'], ...
               sensor_row, sensor_column);
    end

    if ~exist(pattern_source_dir, 'dir')
        error('Pattern source directory does not exist:\n%s', pattern_source_dir);
    end

    % If the user has not specified a destination directory, generate one automatically
    if isempty(pattern_output_dir)
        pattern_output_dir = sprintf('./selected_patterns_4fiber_%dpts', N_select);
    end

    if ~exist(pattern_output_dir, 'dir')
        mkdir(pattern_output_dir);
    else
        old_tifs = dir(fullfile(pattern_output_dir, '*.tif'));

        if ~isempty(old_tifs) && ~allow_existing_tif_in_output
            error(['The destination directory already contains %d TIFF files:\n%s\n' ...
                   'To prevent an old sequence from mixing with this result, please empty the directory, ' ...
                   'or set allow_existing_tif_in_output to true.'], ...
                   numel(old_tifs), pattern_output_dir);
        end
    end

    %% ---------- 8.1 Scan the pattern files generated by Python ----------
    pattern_files = dir(fullfile(pattern_source_dir, '*.tif'));

    if isempty(pattern_files)
        error('No .tif files found in the pattern source directory:\n%s', pattern_source_dir);
    end

    expected_pattern_count = sensor_row * sensor_column;   % 10201

    % Python indices are 0...10200, so the MATLAB cell subscript uses index+1
    pattern_file_by_index = cell(expected_pattern_count, 1);
    pattern_x_by_index = nan(expected_pattern_count, 1);
    pattern_y_by_index = nan(expected_pattern_count, 1);

    % Python save_function file name format:
    % N_1080_index_00000_big_x_126.5_y_210.0.tif
    filename_expr = ...
        '^N_(\d+)_index_(\d+)_big_x_([-+]?\d*\.?\d+)_y_([-+]?\d*\.?\d+)\.tif$';

    matched_file_count = 0;

    for kk = 1:numel(pattern_files)

        this_name = pattern_files(kk).name;
        tok = regexp(this_name, filename_expr, 'tokens', 'once');

        if isempty(tok)
            % Other tif files in the source folder can simply be ignored
            continue;
        end

        py_index0_from_name = str2double(tok{2});
        py_x_from_name = str2double(tok{3});
        py_y_from_name = str2double(tok{4});

        if py_index0_from_name < 0 || py_index0_from_name >= expected_pattern_count
            continue;
        end

        cell_idx = py_index0_from_name + 1;

        if ~isempty(pattern_file_by_index{cell_idx})
            error('Duplicate Python pattern index detected = %d.', py_index0_from_name);
        end

        pattern_file_by_index{cell_idx} = this_name;
        pattern_x_by_index(cell_idx) = py_x_from_name;
        pattern_y_by_index(cell_idx) = py_y_from_name;

        matched_file_count = matched_file_count + 1;
    end

    fprintf('%d patterns matching the naming rule were parsed from the source directory.\n', matched_file_count);

    missing_idx = find(cellfun(@isempty, pattern_file_by_index)) - 1;

    if ~isempty(missing_idx)
        fprintf('The first few missing Python indices: ');
        fprintf('%d ', missing_idx(1:min(20,end)));
        fprintf('\n');

        error(['The Python full-field patterns are incomplete. Expected index 0...%d, i.e., %d patterns in total, ' ...
               'but some indices are missing.'], ...
               expected_pattern_count-1, expected_pattern_count);
    end

    %% ---------- 8.2 MATLAB row/col -> Python pattern index ----------
    %
    % MATLAB:
    %   selected = row + (col-1)*101
    %
    % Python:
    %   outer loop = i0
    %   inner loop = j0   (j0 varies fastest)
    %
    % When mapped to the 101x101 MATLAB storage of the acquired data:
    %
    %   MATLAB row <-> Python j0 (inner)
    %   MATLAB col <-> Python i0 (outer)
    %
    % Therefore:
    %
    %   python_index0 = (col-1)*101 + (row-1)
    %

    selection_order = (1:N_select)';
    matlab_linear_index = selected(:);
    matlab_row = rows(:);
    matlab_col = cols(:);

    python_index0 = zeros(N_select,1);
    python_i0 = zeros(N_select,1);
    python_j0 = zeros(N_select,1);

    expected_big_x = zeros(N_select,1);
    expected_big_y = zeros(N_select,1);

    source_file = cell(N_select,1);
    copied_file = cell(N_select,1);

    % ---------------------------------------------------------
    % First compute the Python index corresponding to every selected point, and complete the mapping verification
    % ---------------------------------------------------------
    for k = 1:N_select

        r_mat = matlab_row(k);
        c_mat = matlab_col(k);

        % Core row/column mapping:
        % MATLAB row <-> Python inner-loop j0
        % MATLAB col <-> Python outer-loop i0
        py_index0 = (c_mat - 1) * sensor_row + (r_mat - 1);

        py_i0 = python_i0_start + (c_mat - 1);
        py_j0 = python_j0_start + (r_mat - 1);

        py_expected_x = py_i0 * python_interval_x;
        py_expected_y = py_j0 * python_interval_y;

        python_index0(k) = py_index0;
        python_i0(k) = py_i0;
        python_j0(k) = py_j0;

        expected_big_x(k) = py_expected_x;
        expected_big_y(k) = py_expected_y;

        lookup_idx = py_index0 + 1;

        this_source_name = pattern_file_by_index{lookup_idx};
        x_in_filename = pattern_x_by_index(lookup_idx);
        y_in_filename = pattern_y_by_index(lookup_idx);

        % Second verification: prevent MATLAB / Python row-column swap
        x_error = abs(x_in_filename - py_expected_x);
        y_error = abs(y_in_filename - py_expected_y);

        if x_error > filename_xy_tolerance || y_error > filename_xy_tolerance

            msg = sprintf([ ...
                'Pattern mapping verification failed!\n' ...
                'MATLAB selection order = %d\n' ...
                'MATLAB row = %d, col = %d\n' ...
                'Computed Python index = %d\n' ...
                'Expected big_x = %.4f, file name big_x = %.4f\n' ...
                'Expected y      = %.4f, file name y      = %.4f\n' ...
                'This usually means the MATLAB/Python row-column mapping or the Python pattern parameters have changed.'], ...
                k, r_mat, c_mat, py_index0, ...
                py_expected_x, x_in_filename, ...
                py_expected_y, y_in_filename);

            if strict_pattern_mapping_check
                error('%s', msg);
            else
                warning('%s', msg);
            end
        end

        % Keep the original Python file name
        source_file{k} = this_source_name;
        copied_file{k} = this_source_name;
    end

    % ---------------------------------------------------------
    % Copy the patterns in ascending order of the original Python index
    %
    % For example, if the random selection is:
    %   [632, 1, 89, 58, 77]
    %
    % the patterns in the destination folder still keep their original names,
    % and when loaded in ascending index / file name order, the sequence is:
    %   1 -> 58 -> 77 -> 89 -> 632
    % ---------------------------------------------------------
    [python_index_sorted, sort_order] = sort(python_index0, 'ascend');

    fprintf('\nStarting to copy %d patterns in ascending order of the original Python index...\n', N_select);
    fprintf('The first few indices: ');
    fprintf('%d ', python_index_sorted(1:min(20,end)));
    fprintf('\n');

    for copy_k = 1:N_select

        k = sort_order(copy_k);

        this_source_name = source_file{k};

        src_path = fullfile(pattern_source_dir, this_source_name);
        dst_path = fullfile(pattern_output_dir, this_source_name);

        if exist(dst_path, 'file') && ~allow_existing_tif_in_output
            error('Destination file already exists:\n%s', dst_path);
        end

        [status, copy_msg] = copyfile(src_path, dst_path, 'f');

        if ~status
            error('Copy failed:\n%s\nMATLAB message: %s', src_path, copy_msg);
        end

        if mod(copy_k,100) == 0 || copy_k == N_select
            fprintf('  Copied %d / %d patterns\n', copy_k, N_select);
        end
    end

    %% ---------- 8.3 Save the mapping manifest ----------
    % projection_order_by_python_index represents the actual loading order in ascending original index
    projection_order_by_python_index = zeros(N_select,1);
    projection_order_by_python_index(sort_order) = (1:N_select)';

    manifest = table( ...
        selection_order, ...
        projection_order_by_python_index, ...
        matlab_linear_index, ...
        matlab_row, ...
        matlab_col, ...
        python_index0, ...
        python_i0, ...
        python_j0, ...
        expected_big_x, ...
        expected_big_y, ...
        source_file, ...
        copied_file, ...
        'VariableNames', { ...
        'random_selection_order', ...
        'projection_order_by_python_index', ...
        'matlab_selected_linear_index', ...
        'matlab_row', ...
        'matlab_col', ...
        'python_index_0based', ...
        'python_i0', ...
        'python_j0', ...
        'expected_big_x', ...
        'expected_y', ...
        'source_file', ...
        'copied_file'});

    % The manifest is also saved in ascending Python index order for direct verification of the projection order
    manifest = sortrows(manifest, 'python_index_0based');

    manifest_csv = fullfile(pattern_output_dir, ...
        sprintf('selected_pattern_manifest_%dpts.csv', N_select));

    writetable(manifest, manifest_csv);

    manifest_mat = fullfile(pattern_output_dir, ...
        sprintf('selected_pattern_manifest_%dpts.mat', N_select));

    % ---------------------------------------------------------
    % Save the "actual projection order" variables for subsequent dynamic imaging
    % ---------------------------------------------------------
    % The original selected / rows / cols store the chronological order of the weighted random sampling,
    % so they are usually not in ascending order. Dynamic projection proceeds in ascending original Python index order.
    % Here, selected / rows / cols / python_index0 in the output MAT are all
    % reordered into the actual projection order, and the original random sampling order is additionally kept for traceability.
    selected_random_order = selected;
    rows_random_order = rows;
    cols_random_order = cols;
    python_index0_random_order = python_index0;

    selected_projection_order = selected(sort_order);
    rows_projection_order = rows(sort_order);
    cols_projection_order = cols(sort_order);
    python_index0_projection_order = python_index0(sort_order);

    % random_chosen_position: 1 x k row vector, saved in the actual projection order.
    % It is directly defined as the Python 0-based pattern index + 1, so for example:
    %   Python index = [1, 58, 77, 89, 632]
    %   random_chosen_position = [2, 59, 78, 90, 633]
    % This variable corresponds one-to-one with the actual loading order of the dynamic-imaging patterns.
    random_chosen_position = reshape(python_index0_projection_order + 1, 1, []);

    % To avoid ambiguity caused by selected in the output MAT,
    % selected / rows / cols / python_index0 are all saved in the actual projection order.
    selected = selected_projection_order;
    rows = rows_projection_order;
    cols = cols_projection_order;
    python_index0 = python_index0_projection_order;

    save(manifest_mat, ...
        'manifest', ...
        'selected', ...
        'rows', ...
        'cols', ...
        'python_index0', ...
        'random_chosen_position', ...
        'selected_random_order', ...
        'rows_random_order', ...
        'cols_random_order', ...
        'python_index0_random_order', ...
        'pattern_source_dir', ...
        'pattern_output_dir');

    % Additionally save a MAT containing only random_chosen_position, so that subsequent programs can read it directly.
    random_position_mat = fullfile(pattern_output_dir, ...
        sprintf('random_chosen_position_%dpts.mat', N_select));
    save(random_position_mat, 'random_chosen_position');

    fprintf('\nPattern copying completed.\n');
    fprintf('Destination directory: %s\n', pattern_output_dir);
    fprintf('Number of copied files: %d\n', N_select);
    fprintf('All TIFF files keep their original Python file names.\n');
    fprintf('When loaded in ascending file name order, the projection order is the ascending Python index order.\n');
    fprintf('selected / rows / cols / python_index0 have been saved in the actual projection order.\n');
    fprintf('random_chosen_position is 1 x %d, and satisfies random_chosen_position = python_index0 + 1.\n', N_select);
    fprintf('random_chosen_position file: %s\n', random_position_mat);
    fprintf('Mapping manifest: %s\n', manifest_csv);

    % Finally, check whether all files corresponding to this manifest exist in the output directory
    missing_after_copy = false;

    for k = 1:N_select
        if ~exist(fullfile(pattern_output_dir, copied_file{k}), 'file')
            missing_after_copy = true;
            warning('Not found after copying: %s', copied_file{k});
        end
    end

    if missing_after_copy
        error('Post-copy integrity check failed; please check the warnings above.');
    else
        fprintf('Post-copy integrity check passed: all %d patterns exist.\n', N_select);
    end

else

    fprintf('\ncopy_selected_patterns_flag = false; pattern copying was not performed.\n');

end